#!/usr/bin/env python3
"""Turn a terrain model's DEM GeoTIFF into an OBJ mesh Gazebo Fortress can actually load.

WHY: Fortress (gz-sim 6) loads <heightmap> collisions only from 8-bit IMAGES. A
float32 GeoTIFF fails with "Unknown image format ... Unable to load image file
as a terrain" and the robot falls to z = 0 with no ground. DEM heightmap support
in physics arrived in Garden. An 8-bit PNG would quantise ~13 m of relief into
5 cm steps. A plain triangle mesh has neither problem and works with every
physics and render engine, so the terrain is a mesh for both visual and
collision.

  python3 scripts/dem_to_mesh.py models/mdrs_terrain    # rewrites meshes/ and model.sdf
  python3 scripts/dem_to_mesh.py --all                  # every *_terrain model

Needs numpy and tifffile (regeneration only, never at sim run time). fetch_dem.py
calls this after writing a new DEM.

Grid convention matches fetch_dem.py's Terrain sampler, so its rock and log
placements sit on this surface: column -> +x (east), row 0 -> +y (north), the
patch centred on the model origin, heights already shifted so min z = 0.
STRIDE 2 turns the 257 x 257 DEM into a 129 x 129 mesh (1.56 m spacing,
32 768 triangles), which keeps llvmpipe rendering and trimesh collision cheap.
"""

import argparse
import glob
import os
import sys

try:
    import numpy as np
    import tifffile
except ImportError as exc:  # pragma: no cover
    sys.exit('dem_to_mesh.py needs numpy and tifffile (%s)' % exc)

STRIDE = 2
UV_TILE_M = 8.0   # texture repeats every 8 m, as the heightmap <texture><size> did

# model dir -> (texture stem, friction, description), matching fetch_dem.py's SITES
SURFACES = {
    'mdrs_terrain': ('desert', 0.9),
    'dunes_terrain': ('sand', 0.7),
}


def write_obj(z, size, mesh_dir, tex):
    n = z.shape[0]
    step = size / (n - 1)
    xs = np.arange(n) * step - size / 2.0
    ys = size / 2.0 - np.arange(n) * step
    gy, gx = np.gradient(z, step)          # d z / d row, d z / d col
    os.makedirs(mesh_dir, exist_ok=True)
    with open(os.path.join(mesh_dir, 'terrain.mtl'), 'w') as fh:
        fh.write('# GENERATED by scripts/dem_to_mesh.py\n'
                 'newmtl terrain\nKa 1 1 1\nKd 1 1 1\nKs 0.05 0.05 0.05\nNs 4\n'
                 'map_Kd ../materials/textures/%s_diffuse.png\n' % tex)
    lines = ['# GENERATED by scripts/dem_to_mesh.py - do not edit, regenerate.',
             'mtllib terrain.mtl', 'o terrain']
    for r in range(n):
        for c in range(n):
            lines.append('v %.3f %.3f %.3f' % (xs[c], ys[r], z[r, c]))
    for r in range(n):
        for c in range(n):
            lines.append('vt %.4f %.4f' % (xs[c] / UV_TILE_M, ys[r] / UV_TILE_M))
    for r in range(n):
        for c in range(n):
            # +y is -row, so the y slope is -gy
            nx, ny, nz = -gx[r, c], gy[r, c], 1.0
            k = (nx * nx + ny * ny + nz * nz) ** 0.5
            lines.append('vn %.4f %.4f %.4f' % (nx / k, ny / k, nz / k))
    lines.append('usemtl terrain')
    for r in range(n - 1):
        for c in range(n - 1):
            a = r * n + c + 1          # OBJ is 1-based
            b, d, e = a + 1, a + n, a + n + 1
            # counter-clockwise seen from above (+z), so normals face up
            lines.append('f %d/%d/%d %d/%d/%d %d/%d/%d' % (a, a, a, d, d, d, b, b, b))
            lines.append('f %d/%d/%d %d/%d/%d %d/%d/%d' % (b, b, b, d, d, d, e, e, e))
    with open(os.path.join(mesh_dir, 'terrain.obj'), 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    return n, 2 * (n - 1) ** 2


def model_sdf(name, size, relief, mu):
    mesh = '<mesh><uri>model://%s/meshes/terrain.obj</uri></mesh>' % name
    return '''<?xml version="1.0"?>
<!-- GENERATED by scripts/dem_to_mesh.py from dem/*_dem.tif (see README.md for the source).
     %(size)g x %(size)g m terrain, lowest point z = 0, relief %(relief).3f m. A mesh, not a
     heightmap - Fortress cannot load a float DEM as a physics heightmap. -->
<sdf version="1.8">
  <model name="%(name)s">
    <static>true</static>
    <link name="link">
      <collision name="collision">
        <geometry>%(mesh)s</geometry>
        <surface><friction><ode><mu>%(mu)g</mu><mu2>%(mu)g</mu2></ode></friction></surface>
      </collision>
      <visual name="visual">
        <geometry>%(mesh)s</geometry>
      </visual>
    </link>
  </model>
</sdf>
''' % dict(name=name, size=size, relief=relief, mesh=mesh, mu=mu)


def convert(model_dir, size=200.0):
    name = os.path.basename(os.path.normpath(model_dir))
    tifs = glob.glob(os.path.join(model_dir, 'dem', '*_dem.tif'))
    if len(tifs) != 1:
        sys.exit('%s: expected exactly one dem/*_dem.tif, found %d' % (model_dir, len(tifs)))
    z = tifffile.imread(tifs[0]).astype(np.float64)
    z = z - z.min()
    z = z[::STRIDE, ::STRIDE]
    tex, mu = SURFACES.get(name, ('desert', 0.9))
    n, tris = write_obj(z, size, os.path.join(model_dir, 'meshes'), tex)
    with open(os.path.join(model_dir, 'model.sdf'), 'w') as fh:
        fh.write(model_sdf(name, size, float(z.max()), mu))
    print('%s: %dx%d grid, %d triangles, relief %.2f m' % (name, n, n, tris, z.max()))


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('model_dirs', nargs='*')
    p.add_argument('--all', action='store_true', help='every models/*_terrain')
    p.add_argument('--size', type=float, default=200.0, help='patch edge length, m')
    a = p.parse_args()
    dirs = a.model_dirs
    if a.all:
        here = os.path.dirname(os.path.abspath(__file__))
        dirs = sorted(glob.glob(os.path.join(here, '..', 'models', '*_terrain')))
    if not dirs:
        p.error('give model dirs or --all')
    for d in dirs:
        convert(d, a.size)


if __name__ == '__main__':
    main()
